import type { ExamExerciseConfig, ExamQuestion } from "@/types/practice";

function mcq(
  number: number,
  prompt: string,
  options: [string, string, string, string],
  topic: string,
  points = 0.2,
): ExamQuestion {
  return {
    id: `q${number}`,
    number,
    kind: "multiple_choice",
    prompt,
    points,
    topic,
    options: [
      { id: "A", label: options[0] },
      { id: "B", label: options[1] },
      { id: "C", label: options[2] },
      { id: "D", label: options[3] },
    ],
  };
}

function readingMcq(
  number: number,
  prompt: string,
  options: [string, string, string, string],
  topic: string,
): ExamQuestion {
  return {
    id: `q${number}`,
    number,
    kind: "reading",
    prompt,
    points: 0.5,
    topic,
    passageId: "minh",
    options: [
      { id: "A", label: options[0] },
      { id: "B", label: options[1] },
      { id: "C", label: options[2] },
      { id: "D", label: options[3] },
    ],
  };
}

